-- Run this in Supabase SQL Editor.
create table if not exists public.bevo_media (
  id bigint generated by default as identity primary key,
  title text not null,
  type text not null check (type in ('movie','series')),
  interpreter_id text,
  interpreter_name text,
  image_url text,
  description text,
  telegram_file_id text not null,
  episodes jsonb not null default '[]'::jsonb,
  published boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.bevo_media enable row level security;

-- Everyone can read published titles. Only the configured admin can insert/update/delete.
create policy "Public can read published BevoFilms media"
on public.bevo_media for select
using (published = true);

-- Replace YOUR_ADMIN_USER_UUID with the Auth user's UUID.
create policy "Only BevoFilms admin can insert"
on public.bevo_media for insert to authenticated
with check (auth.uid() = 'YOUR_ADMIN_USER_UUID'::uuid);

create policy "Only BevoFilms admin can update"
on public.bevo_media for update to authenticated
using (auth.uid() = 'YOUR_ADMIN_USER_UUID'::uuid)
with check (auth.uid() = 'YOUR_ADMIN_USER_UUID'::uuid);

create policy "Only BevoFilms admin can delete"
on public.bevo_media for delete to authenticated
using (auth.uid() = 'YOUR_ADMIN_USER_UUID'::uuid);
